function projectTarget(button, x, y, height = 0) {
  if (!garden3D) return;
  const point = garden3D.project(x, y, height);
  const rect = ui.scene.getBoundingClientRect();
  const halfWidth = button.offsetWidth / 2 || 22, halfHeight = button.offsetHeight / 2 || 22;
  button.style.left = `${Math.max(halfWidth, Math.min(rect.width - halfWidth, point.x))}px`;
  button.style.top = `${Math.max(halfHeight, Math.min(rect.height - halfHeight, point.y))}px`;
  button.style.visibility = point.visible ? 'visible' : 'hidden';
  button.dataset.projectX = String(point.x); button.dataset.projectY = String(point.y);
  button.style.zIndex = String(Math.round(point.y));
}
