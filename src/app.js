function onPlot(index) {
  const plant = plantAt(index);
  if (activeTool === 'propagate') {
    if (plant) { showToast('Choose an empty plot for the new seedling.'); return; }
    if (propagationParentIndex === null) { showToast('Select a mature specimen to propagate first.'); return; }
    const parent = propagationParentIndex;
    const result = propagatePlant(state, parent, index);
    if (result?.ok) { selectedIndex = index; propagationParentIndex = null; setTool('inspect'); }
    resultMessage(result, 'plant'); return;
  }
  if (activeTool === 'plant' && !plant) {
    if (!selectedSeed) { showToast('Choose a seed from the nursery first.'); return; }
    const result = plantSeed(state, index, selectedSeed);
    if (result?.ok && !guide.planted) { guide.planted = true; saveGuide(); }
    selectedIndex = index; resultMessage(result, 'plant'); return;
  }
  if (activeTool === 'water' && plant) { selectedIndex = index; resultMessage(waterPlant(state, index), 'water'); return; }
  if (activeTool === 'feed' && plant) { selectedIndex = index; resultMessage(feedPlant(state, index), 'feed'); return; }
  selectedIndex = index; render();
  // On phones the plant panel sits below the garden; bring its actions into view.
  if (plant && !combatBusy() && matchMedia('(max-width: 700px)').matches) revealElement($('plant-detail'));
}
