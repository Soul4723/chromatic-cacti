function tickDefense() {
  if (document.hidden) return;
  const beforeStatus = state.combat.status, beforeLevel = state.combat.level, beforeWave = state.combat.wave;
  const beforeCredits = state.credits, beforeEssence = state.essence;
  const tick = tickCombat(state, .1);
  if (tick.changed) {
    syncCombatPlantChanges(); renderCombatActors(); renderCombatHud(); renderResources();
    if (reducedMotion) drawScene(performance.now());
    if (state.credits !== beforeCredits || state.essence !== beforeEssence || state.combat.level !== beforeLevel || state.combat.wave !== beforeWave) renderManagement();
  }
  // Background events (nibbles, spawns) never overwrite the player's own hit feedback right away.
  if (tick.events?.length && performance.now() >= playerFeedbackUntil) {
    const eventText = tick.events.slice(-2).join(' ');
    combatFeedback = eventText;
    setCombatMessage(eventText);
  }
  if (tick.events?.some((event) => event.includes('summoned an earwig'))) playSound('boss');
  const phaseChanged = beforeStatus !== state.combat.status || beforeLevel !== state.combat.level || beforeWave !== state.combat.wave;
  if (phaseChanged) {
    if (state.combat.status === 'defeat') playSound('defeat');
    else if (state.combat.level > beforeLevel) playSound('levelup');
    else if (beforeStatus === 'active' && ['cleared', 'champion'].includes(state.combat.status)) playSound('waveclear');
    if (!tick.events?.length) combatFeedback = state.combat.message || '';
    render(); showToast(state.combat.message || `Level ${state.combat.level}, wave ${state.combat.wave || 1}.`, ['cleared', 'champion'].includes(state.combat.status)); saveCombatNow();
  }
  else if ((state.combat.status === 'active' || tick.events?.length) && performance.now() - lastCombatSave >= 2000) saveCombatNow();
}
