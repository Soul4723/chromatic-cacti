function syncActorLayer(layer, map, actors, kind, fallback) {
  const live = new Set(actors.map((actor) => actor.id));
  const focusedId = [...map].find(([, button]) => document.activeElement === button)?.[0];
  for (const [id, button] of map) if (!live.has(id)) { button.remove(); map.delete(id); }
  for (const actor of actors) actorButton(layer, map, actor, kind);
  if (focusedId && !map.has(focusedId)) {
    const candidates = [
      ...map.values(),
      $(kind === 'worm' ? 'plot-layer' : fallback)?.querySelector?.('.plot-button'),
      $(fallback),
      ...document.querySelectorAll('#plot-layer .plot-button, #seed-list button, #stomp-mode, #dock-stomp'),
    ];
    const target = candidates.find((button) => button instanceof HTMLElement && button !== document.activeElement &&
      !button.disabled && button.isConnected && button.getClientRects().length &&
      getComputedStyle(button).visibility !== 'hidden');
    target?.focus({ preventScroll: true });
  }
}
