function saveGame(quiet = true) {
  try {
    const payload = JSON.parse(serializeGame(state));
    payload.progress = state.progress;
    payload.combat = state.combat;
    localStorage.setItem(SAVE_KEY, JSON.stringify(payload));
    if (!quiet) showToast('Garden saved in this browser.');
  } catch (error) { console.error('Could not save the local garden:', error); showToast('Browser storage is unavailable. Your garden is still open.'); }
}
