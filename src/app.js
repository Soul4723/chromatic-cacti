function syncCombatPlantChanges() {
  let rebuild = false;
  for (let index = 0; index < state.plots.length; index++) {
    const button = ui.plots.querySelector(`[data-plot-index="${index}"]`), plant = state.plots[index];
    if (!button || (!!plant !== !button.classList.contains('empty'))) { rebuild = true; break; }
    const signature = plantSignature(plant);
    if (button.dataset.signature === signature) continue;
    button.dataset.signature = signature;
    if (plant) {
      button.setAttribute('aria-label', `Plot ${index + 1}: ${plantName(plant)}, ${Math.round(plant.growth)}% grown, ${Math.round(plant.health)}% health, ${Math.round(plant.moisture)}% moisture${selectedIndex === index ? ', selected' : ''}`);
      button.querySelector('.plot-label').textContent = `${plantName(plant)} · ${Math.round(plant.growth)}%`;
    }
    if (selectedIndex === index && plant) {
      $('growth-value').textContent = `${Math.round(plant.growth)}%`; $('growth-meter').style.width = `${plant.growth}%`;
      $('health-value').textContent = `${Math.round(plant.health)}%`; $('moisture-value').textContent = `${Math.round(plant.moisture)}%`;
      $('plant-status').textContent = plantStatus(plant);
    }
  }
  if (rebuild) { renderPlots(); if (selectedIndex !== null && !state.plots[selectedIndex]) renderDetail(); }
}
function performAttack(x, y) {
  const beforeStatus = state.combat.status, beforeLevel = state.combat.level, beforeWave = state.combat.wave;
  const weapon = selectedWeapon;
  const stats = getDefenseStats(state);
  const hitEnemies = state.combat.enemies.filter((enemy) => {
    const radius = weapon === 'stomp' ? stats.stompRadius : stats.sprayRadius;
    return Math.hypot(enemy.x - x, enemy.y - y) <= radius && (weapon !== 'stomp' || !enemy.airborne);
  });
  const healthBefore = hitEnemies.reduce((total, enemy) => total + enemy.hp, 0);
  const result = attackAt(state, selectedWeapon, x, y);
  if (!result?.ok) { combatFeedback = result?.message || 'That attack is not ready.'; renderCombatHud(); return; }
  combatFeedback = `${result.message}${result.kills ? ` · ${result.kills} defeated` : ''}`;
  playerFeedbackUntil = performance.now() + 1400;
  setCombatMessage(combatFeedback);
  const element = document.createElement('canvas'); element.className = `defense-impact ${selectedWeapon}`; element.width = 240; element.height = 180; element.setAttribute('aria-hidden', 'true'); Object.assign(element.style, { border: '0', borderRadius: '0', background: 'none', boxShadow: 'none' }); $('effect-layer').append(element);
  defenseEffects.push({ weapon: selectedWeapon, x, y, hits: result.hits, kills: result.kills, damage: healthBefore - hitEnemies.reduce((total, enemy) => total + Math.max(0, enemy.hp), 0), radius: selectedWeapon === 'stomp' ? stats.stompRadius : stats.sprayRadius, createdAt: performance.now(), element });
  if (reducedMotion) setTimeout(() => { element.remove(); const index = defenseEffects.findIndex((effect) => effect.element === element); if (index >= 0) defenseEffects.splice(index, 1); }, 700);
  drawScene(performance.now());
  const shellHit = weapon === 'stomp' && hitEnemies.some((enemy) => enemy.type === 'snail');
  const sound = !result.hits ? 'miss' : result.kills ? 'pest' : shellHit ? 'shell' : weapon;
  playSound(sound);
  if (state.combat.level > beforeLevel) playSound('levelup'); else if (beforeStatus === 'active' && ['cleared', 'champion'].includes(state.combat.status)) playSound('waveclear');
  if (beforeStatus !== state.combat.status || beforeLevel !== state.combat.level || beforeWave !== state.combat.wave) { combatFeedback = `${state.combat.message} ${combatFeedback}`.trim(); render(); }
  else { renderCombatHud(); renderCombatActors(); renderResources(); }
  saveCombatNow();
}
